def xh_decode(xh):
    """Reproduce the payload decoding performed inside ``WH``.

    ``WH`` performs ``string.gsub(string.sub(XH, 5), DH, kH)``.  Lua's gsub
    scans left to right and does not rescan text it has just inserted, so the
    transformation is exactly one left-to-right pass over the *original*
    string, replacing each single character of ``[ v-~]`` by its 5 character
    blob.  Because the replacement blob itself may contain characters of the
    pattern, a naive regex substitution differs from the real thing.
    """
    out = []
    for ch in xh[4:]:
        out.append(KEYS.get(ch, ch))
    return "".join(out)


def sbox_step(d, v, f):
    """One step of the ``qH`` table generator.

    ``qH`` computes, for a state triple, ``s = (c*v + d) % 256`` and stores it
    both into ``uv13.CH[F]`` and (packed with three more bytes) into ``tab.Z[F]``.
    """
    y = (d + v * f) % 256
    k = (d + v * y) % 256
    c = (d + v * k) % 256
    s = (c * v + d) % 256
    return s
